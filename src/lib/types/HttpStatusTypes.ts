import { HTTP_STATUS } from '../constants/HttpStatusConstants';
// ∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞

export type StatusCodeType = typeof HTTP_STATUS;

export type HttpStatus = StatusCodeType[keyof StatusCodeType];

export type SuccessHttpStatus =
	| typeof HTTP_STATUS.OK
	| typeof HTTP_STATUS.CREATED
	| typeof HTTP_STATUS.ACCEPTED
	| typeof HTTP_STATUS.NO_CONTENT;

export type FailureHttpStatus = Exclude<
	HttpStatus,
	| SuccessHttpStatus
	| typeof HTTP_STATUS.MOVED_PERMANENTLY
	| typeof HTTP_STATUS.FOUND
>;

import { useToast } from 'primevue/usetoast';
// ∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞

type LiveDataErrorToastOptions = {
	summary: string;
};

type LiveDataErrorToast = {
	showLiveDataErrorToast: (message: string) => void;
};
// ∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞

// --- Return an explicit action so creating or remounting the component never displays a toast. ---
export const UseLiveDataErrorToastComposable = ({
	summary,
}: LiveDataErrorToastOptions): LiveDataErrorToast => {
	const toast = useToast();

	const showLiveDataErrorToast = (message: string): void => {
		toast.add({
			severity: 'error',
			summary,
			detail: message,
			life: 6000,
		});
	};

	const liveDataErrorToast: LiveDataErrorToast = {
		showLiveDataErrorToast,
	};

	return liveDataErrorToast;
};
// ∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞∞

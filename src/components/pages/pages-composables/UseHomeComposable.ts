export const UseHomeComposable = () => {
	const mainContainerStyleClasses = twMerge(
		clsx(
			'relative min-h-screen w-full overflow-hidden',
			'bg-transparent text-slate-950',
			'dark:text-white',
		),
	);

	return {
		mainContainerStyleClasses,
	};
};
